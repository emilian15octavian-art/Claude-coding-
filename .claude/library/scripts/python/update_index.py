#!/usr/bin/env python3
"""Regenerate the auto section of the brain's library INDEX.md (zero LLM tokens).

Scans $BRAIN/skills/*/SKILL.md, $BRAIN/library/prompts/**, $BRAIN/library/scripts/**
and the repo's .mcp.json, then rewrites only the rows between the AUTO markers in
$BRAIN/library/INDEX.md. Rows outside the markers are kept as written by hand.

Works as a PostToolUse hook (reads the hook JSON on stdin and exits early unless the
edited file is inside the brain) or standalone: `python3 update_index.py`.
"""
import json
import os
import sys
from datetime import date
from pathlib import Path

START = "<!-- AUTO-INDEX:START (generated by update_index.py, do not edit by hand) -->"
END = "<!-- AUTO-INDEX:END -->"
HEADER = "| Artifact | Category | Path | Purpose | Updated |\n| :--- | :--- | :--- | :--- | :--- |"


def find_brain() -> Path:
    env = os.environ.get("CLAUDE_BRAIN")
    if env:
        return Path(env).expanduser()
    for base in (os.environ.get("CLAUDE_PROJECT_DIR"), os.getcwd()):
        if base:
            cand = Path(base) / ".claude"
            if (cand / "skills" / "autonomous-core").is_dir():
                return cand
    return Path.home() / ".claude"


def edited_path_from_stdin():
    if sys.stdin is None or sys.stdin.isatty():
        return None
    try:
        import select
        ready, _, _ = select.select([sys.stdin], [], [], 1.0)
    except (ValueError, OSError, ImportError):
        ready = [sys.stdin]  # e.g. Windows pipes: fall back to a plain read
    if not ready:
        return None  # stdin left open with nothing on it: run as standalone
    try:
        data = json.loads(sys.stdin.read() or "null") or {}
    except (ValueError, OSError):
        return None
    if not isinstance(data, dict):
        return None
    tool_input = data.get("tool_input") or {}
    return tool_input.get("file_path") or tool_input.get("notebook_path")


def updated(path: Path) -> str:
    return date.fromtimestamp(path.stat().st_mtime).isoformat()


def cell(text: str) -> str:
    text = " ".join(text.split()).replace("|", "\\|")
    return text[:157] + "..." if len(text) > 160 else text


def frontmatter(path: Path) -> dict:
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    out = {}
    if lines and lines[0].strip() == "---":
        for line in lines[1:]:
            if line.strip() == "---":
                break
            if ":" in line:
                key, val = line.split(":", 1)
                out[key.strip()] = val.strip().strip("\"'")
    return out


def first_meaningful_line(path: Path) -> str:
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    in_doc = False
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith("#!") or line == "---":
            continue
        if line.startswith(('"""', "'''")):
            body = line.strip("\"'").strip()
            if body:
                return body
            in_doc = True
            continue
        if in_doc:
            return line
        return line.lstrip("#/*-; ").strip()
    return ""


def rows(brain: Path, root: Path) -> list:
    out = []
    rel = lambda p: os.path.relpath(p, root)
    for skill in sorted((brain / "skills").glob("*/SKILL.md")):
        fm = frontmatter(skill)
        out.append(("skill", fm.get("name", skill.parent.name), rel(skill), fm.get("description", ""), updated(skill)))
    for kind in ("prompts", "scripts"):
        base = brain / "library" / kind
        if not base.is_dir():
            continue
        for f in sorted(p for p in base.rglob("*") if p.is_file() and not p.name.startswith(".")):
            category = f"{kind[:-1]}/{f.parent.name}"
            out.append((category, f.stem, rel(f), first_meaningful_line(f), updated(f)))
    mcp = root / ".mcp.json"
    if mcp.is_file():
        try:
            servers = json.loads(mcp.read_text()).get("mcpServers", {})
        except ValueError:
            servers = {}
        for name, cfg in sorted(servers.items()):
            cmd = " ".join([cfg.get("command", "")] + cfg.get("args", [])).strip() or cfg.get("url", "")
            out.append(("mcp", name, rel(mcp), f"MCP server: `{cmd}`", updated(mcp)))
    return [f"| {cell(a)} | {cell(c)} | `{p}` | {cell(d)} | {u} |" for c, a, p, d, u in out]


def main() -> int:
    brain = find_brain().resolve()
    edited = edited_path_from_stdin()
    if edited is not None:
        try:
            Path(edited).resolve().relative_to(brain)
        except ValueError:
            if Path(edited).name != ".mcp.json":
                return 0
    index = brain / "library" / "INDEX.md"
    if not index.parent.is_dir():
        return 0
    root = brain.parent if brain.name == ".claude" and brain != Path.home() / ".claude" else brain
    block = "\n".join([START, HEADER, *rows(brain, root), END])
    text = index.read_text(encoding="utf-8") if index.exists() else "# Master Library Index\n"
    if START in text and END in text:
        head, rest = text.split(START, 1)
        tail = rest.split(END, 1)[1]
        new = head + block + tail
    else:
        new = text.rstrip("\n") + "\n\n" + block + "\n"
    if new != text:
        index.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
